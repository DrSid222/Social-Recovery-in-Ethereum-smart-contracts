def solved(title, p, key, note=""):
    r = analyse(p, trace=True)
    out.append(f"### {title}\n{note}\nParameters: n={p.n}, b={p.b}, slots M,S1,S2={p.slots}, r={p.r}, g={p.g}, D1={p.D1*12}h, D2={p.D2*12}h, GC delay={p.GCd*12}h, move order={'attacker first' if p.first==ATK else 'owner first'}\n"
               f"Result: {key} reached in {r[key]*12 if r[key] is not None else None}h (optimal play for both sides)\n```")
    tr = r[key + "_trace"]; clean = []
    import re
    for line in tr:
        if clean and re.fullmatch(r"t=\d+: (BG|HG): lock", clean[-1]) and re.fullmatch(r"t=\d+: (BG|HG): unlock", line):
            clean.pop(); continue
        clean.append(line)
    out.extend(clean); out.append("```\n")

def replay(title, p, script, note=""):
    """Deterministic replay of a hand-written script through the same rules (independent check of the semantics)."""
    c = init_core(p); turn_log = [f"### {title}\n{note}\n```"]
    t = 0
    for step in script:
        if step == "tick":
            c = tick(c, p); t += 1; turn_log.append(f"-- tick {t} (+12h) --"); continue
        side, prefix = step
        opts = moves(c, side, p)
        pick = [o for o in opts if o[0].startswith(prefix)]
        if not pick:
            turn_log.append(f"t={t}: !! '{prefix}' NOT AVAILABLE for {'attacker' if side==ATK else 'owner'}; available: {[o[0] for o in opts]}")
            continue
        c = pick[0][1]; turn_log.append(f"t={t}: {pick[0][0]}")
    turn_log.append(f"final: slots(M,S1,S2)={c[:3]} phase2={c[PH2]} recovery_pending_holder={c[RECH]} loss={c[LOSS]} capture_flags={c[CAP]} bad_guardians={c[B]} clean={is_clean(c)}")
    turn_log.append("```\n"); out.extend(turn_log)

